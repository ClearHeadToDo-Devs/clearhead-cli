//! Telemetry module for semantic event logging.
//!
//! This module implements the observability specification for ClearHead tooling,
//! providing semantic event logging for debugging, analytics, and audit trails.
//!
//! # Overview
//!
//! Events are stored as newline-delimited JSON (NDJSON) in XDG state directory:
//! - **Linux/macOS:** `~/.local/state/clearhead/telemetry/events-YYYY-MM.ndjson`
//! - **Windows:** `%LOCALAPPDATA%\clearhead\state\telemetry\events-YYYY-MM.ndjson`
//!
//! Files rotate monthly by default for easy archival and querying.
//!
//! # Event Categories
//!
//! - **Action Lifecycle:** created, completed, cancelled, started, blocked, restarted, deleted
//! - **Property Changes:** priority_changed, due_date_changed, name_changed, context_added/removed
//! - **Recurring Actions:** instance_generated, instance_completed, instance_skipped, template_edited
//! - **Sync Operations:** sync_started, sync_completed, sync_failed, conflict_resolved
//! - **System Events:** workspace_opened, file_parsed, lsp_started
//!
//! # Usage
//!
//! ```rust,ignore
//! use clearhead_cli::telemetry::{emit_event, TelemetryEvent, Tool};
//!
//! // Emit an event with the current timestamp
//! emit_event(
//!     Tool::Cli,
//!     Some("action-uuid".to_string()),
//!     TelemetryEvent::ActionCreated {
//!         name: "My task".to_string(),
//!         file_path: "inbox.actions".to_string(),
//!     },
//! )?;
//! ```
//!
//! # Output Format
//!
//! Each line in the NDJSON file is a complete JSON object:
//!
//! ```json
//! {"timestamp":"2026-01-30T10:30:00+00:00","tool":"cli","action_uuid":"...","event":"action_created","name":"...","file_path":"..."}
//! ```
//!
//! Events can be queried with standard tools like DuckDB or jq:
//!
//! ```bash
//! # Count events by type
//! jq -s 'group_by(.event) | map({event: .[0].event, count: length})' events-2026-01.ndjson
//!
//! # Find all completions for an action
//! jq 'select(.action_uuid == "abc-123" and .event == "action_completed")' events-2026-01.ndjson
//! ```
//!
//! # Relationship to Other Concerns
//!
//! - **CRDT (Automerge):** Handles coordination and conflict resolution
//! - **Domain Files (.actions):** Human-readable state, queryable
//! - **Telemetry (this module):** Debugging, analytics, audit trail
//!
//! These are complementary. CRDT tracks *operational* history (insertions, deletions).
//! Telemetry tracks *semantic* history (what those operations meant in domain terms).

