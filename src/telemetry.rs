/// Convert a [`FieldChange`] to a [`TelemetryEvent`], if applicable.
///
/// Returns `None` for field changes that don't have a corresponding telemetry event
/// (e.g., description changes, context changes that need special handling).
///
/// # Example
///
/// ```rust,ignore
/// use clearhead_cli::diff::FieldChange;
/// use clearhead_cli::telemetry::event_from_field_change;
///
/// let change = FieldChange::Priority { old: Some(2), new: Some(1) };
/// if let Some(event) = event_from_field_change(&change) {
///     emit_event(Tool::Cli, Some(action_id), event)?;
/// }
/// ```
pub fn event_from_field_change(change: &FieldChange) -> Option<TelemetryEvent> {
    match change {
        FieldChange::Name { old, new } => Some(TelemetryEvent::NameChanged {
            old_name: old.clone(),
            new_name: new.clone(),
        }),
        FieldChange::Priority { old, new } => Some(TelemetryEvent::PriorityChanged {
            old_priority: *old,
            new_priority: *new,
        }),
        FieldChange::DoDate { old, new } => Some(TelemetryEvent::DueDateChanged {
            old_date: old.clone(),
            new_date: new.clone(),
        }),
        // State changes are handled separately via event_from_state_change
        // to allow passing the action name
        FieldChange::State { .. } => None,
        // Other field changes not yet mapped to events
        _ => None,
    }
}

/// Convert an [`ActionState`] transition to a [`TelemetryEvent`], if applicable.
///
/// Returns `None` for state transitions that don't have semantic meaning
/// (e.g., NotStarted → NotStarted).
///
/// # Arguments
///
/// * `old` - The previous state
/// * `new` - The new state
/// * `name` - The action name (used in the event payload)
///
/// # Example
///
/// ```rust,ignore
/// use clearhead_cli::entities::ActionState;
/// use clearhead_cli::telemetry::event_from_state_change;
///
/// let event = event_from_state_change(
///     ActionState::NotStarted,
///     ActionState::Completed,
///     "My task",
/// );
/// ```
pub fn event_from_state_change(
    old: ActionState,
    new: ActionState,
    name: &str,
) -> Option<TelemetryEvent> {
    match (old, new) {
        // Completing an action
        (_, ActionState::Completed) => Some(TelemetryEvent::ActionCompleted {
            name: name.to_string(),
            completed_at: Utc::now().to_rfc3339(),
        }),
        // Starting an action
        (_, ActionState::InProgress) => Some(TelemetryEvent::ActionStarted {
            name: name.to_string(),
        }),
        // Blocking an action
        (_, ActionState::BlockedorAwaiting) => Some(TelemetryEvent::ActionBlocked {
            name: name.to_string(),
            reason: None,
        }),
        // Cancelling an action
        (_, ActionState::Cancelled) => Some(TelemetryEvent::ActionCancelled {
            name: name.to_string(),
            reason: None,
        }),
        // Restarting a completed action
        (ActionState::Completed, ActionState::NotStarted) => {
            Some(TelemetryEvent::ActionRestarted {
                name: name.to_string(),
                reason: None,
            })
        }
        // No semantic event for other transitions
        _ => None,
    }
}

