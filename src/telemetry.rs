/// Tool identifier indicating the source of an event.
///
/// This helps distinguish events generated by different ClearHead tools
/// when analyzing telemetry data.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum Tool {
    /// Command-line interface
    Cli,
    /// Language Server Protocol implementation
    Lsp,
    /// Sync daemon or operation
    Sync,
}

/// Semantic events as defined in the observability specification.
///
/// Each variant corresponds to a meaningful domain event that provides
/// value for debugging, analytics, or audit purposes.
///
/// Events are serialized with a `"event"` field containing the snake_case event name.
#[derive(Debug, Clone, PartialEq, Serialize)]
#[serde(tag = "event")]
pub enum TelemetryEvent {
    // =========================================================================
    // Action Lifecycle Events
    // =========================================================================
    /// A new action was created.
    #[serde(rename = "action_created")]
    ActionCreated {
        /// Name of the created action
        name: String,
        /// Path to the file containing the action
        file_path: String,
    },

    /// An action was marked as completed.
    #[serde(rename = "action_completed")]
    ActionCompleted {
        /// Name of the completed action
        name: String,
        /// ISO 8601 timestamp when completion occurred
        completed_at: String,
    },

    /// An action was cancelled.
    #[serde(rename = "action_cancelled")]
    ActionCancelled {
        /// Name of the cancelled action
        name: String,
        /// Optional reason for cancellation
        #[serde(skip_serializing_if = "Option::is_none")]
        reason: Option<String>,
    },

    /// An action was started (moved to in_progress state).
    #[serde(rename = "action_started")]
    ActionStarted {
        /// Name of the started action
        name: String,
    },

    /// An action was blocked (moved to blocked/awaiting state).
    #[serde(rename = "action_blocked")]
    ActionBlocked {
        /// Name of the blocked action
        name: String,
        /// Optional reason for blocking
        #[serde(skip_serializing_if = "Option::is_none")]
        reason: Option<String>,
    },

    /// A completed action was restarted (moved back to not_started).
    #[serde(rename = "action_restarted")]
    ActionRestarted {
        /// Name of the restarted action
        name: String,
        /// Optional reason for restarting
        #[serde(skip_serializing_if = "Option::is_none")]
        reason: Option<String>,
    },

    /// An action was deleted from a file.
    #[serde(rename = "action_deleted")]
    ActionDeleted {
        /// Name of the deleted action
        name: String,
    },

    // =========================================================================
    // Property Change Events
    // =========================================================================
    /// An action's priority was changed.
    #[serde(rename = "priority_changed")]
    PriorityChanged {
        /// Previous priority value (None if unset)
        old_priority: Option<u32>,
        /// New priority value (None if cleared)
        new_priority: Option<u32>,
    },

    /// An action's due date was changed.
    #[serde(rename = "due_date_changed")]
    DueDateChanged {
        /// Previous due date (ISO 8601, None if unset)
        old_date: Option<String>,
        /// New due date (ISO 8601, None if cleared)
        new_date: Option<String>,
    },

    /// An action was renamed.
    #[serde(rename = "name_changed")]
    NameChanged {
        /// Previous name
        old_name: String,
        /// New name
        new_name: String,
    },

    /// A context tag was added to an action.
    #[serde(rename = "context_added")]
    ContextAdded {
        /// The context tag that was added
        context: String,
    },

    /// A context tag was removed from an action.
    #[serde(rename = "context_removed")]
    ContextRemoved {
        /// The context tag that was removed
        context: String,
    },

    // =========================================================================
    // Recurring Action Events
    // =========================================================================
    /// A new instance was generated from a recurring template.
    #[serde(rename = "instance_generated")]
    InstanceGenerated {
        /// UUID of the recurring template
        template_uuid: String,
        /// Date of the generated occurrence (ISO 8601)
        occurrence_date: String,
    },

    /// A recurring action instance was completed.
    #[serde(rename = "instance_completed")]
    InstanceCompleted {
        /// UUID of the recurring template
        template_uuid: String,
        /// Originally scheduled date (ISO 8601)
        scheduled_date: String,
        /// Actual completion date (ISO 8601)
        completed_date: String,
    },

    /// A recurring action occurrence was skipped.
    #[serde(rename = "instance_skipped")]
    InstanceSkipped {
        /// UUID of the recurring template
        template_uuid: String,
        /// Date of the skipped occurrence (ISO 8601)
        occurrence_date: String,
        /// Optional reason for skipping
        #[serde(skip_serializing_if = "Option::is_none")]
        reason: Option<String>,
    },

    /// A recurring action template was edited.
    #[serde(rename = "template_edited")]
    TemplateEdited {
        /// UUID of the recurring template
        template_uuid: String,
        /// List of field names that were changed
        fields_changed: Vec<String>,
    },

    // =========================================================================
    // Sync Events
    // =========================================================================
    /// A sync operation started.
    #[serde(rename = "sync_started")]
    SyncStarted {
        /// Remote endpoint identifier
        remote: String,
        /// Direction: "push", "pull", or "bidirectional"
        direction: String,
    },

    /// A sync operation completed successfully.
    #[serde(rename = "sync_completed")]
    SyncCompleted {
        /// Remote endpoint identifier
        remote: String,
        /// Number of changes sent to remote
        changes_sent: u32,
        /// Number of changes received from remote
        changes_received: u32,
    },

    /// A sync operation failed.
    #[serde(rename = "sync_failed")]
    SyncFailed {
        /// Remote endpoint identifier
        remote: String,
        /// Error message describing the failure
        error: String,
    },

    /// A CRDT conflict was automatically resolved.
    #[serde(rename = "conflict_resolved")]
    ConflictResolved {
        /// UUID of the action with the conflict
        action_uuid: String,
        /// Description of how the conflict was resolved
        resolution: String,
    },

    // =========================================================================
    // System Events
    // =========================================================================
    /// A workspace was opened.
    #[serde(rename = "workspace_opened")]
    WorkspaceOpened {
        /// Path to the workspace root
        path: String,
        /// Number of actions loaded
        action_count: usize,
    },

    /// An actions file was parsed.
    #[serde(rename = "file_parsed")]
    FileParsed {
        /// Path to the parsed file
        file_path: String,
        /// Number of actions in the file
        action_count: usize,
        /// Time taken to parse in milliseconds
        parse_time_ms: u64,
    },

    /// The LSP server started.
    #[serde(rename = "lsp_started")]
    LspStarted {
        /// Port number if using TCP transport
        #[serde(skip_serializing_if = "Option::is_none")]
        port: Option<u16>,
    },
}

impl TelemetryEvent {
    /// Get the event type name for logging and filtering purposes.
    ///
    /// Returns the snake_case event name matching the JSON serialization.
    pub fn name(&self) -> &'static str {
        match self {
            TelemetryEvent::ActionCreated { .. } => "action_created",
            TelemetryEvent::ActionCompleted { .. } => "action_completed",
            TelemetryEvent::ActionCancelled { .. } => "action_cancelled",
            TelemetryEvent::ActionStarted { .. } => "action_started",
            TelemetryEvent::ActionBlocked { .. } => "action_blocked",
            TelemetryEvent::ActionRestarted { .. } => "action_restarted",
            TelemetryEvent::ActionDeleted { .. } => "action_deleted",
            TelemetryEvent::PriorityChanged { .. } => "priority_changed",
            TelemetryEvent::DueDateChanged { .. } => "due_date_changed",
            TelemetryEvent::NameChanged { .. } => "name_changed",
            TelemetryEvent::ContextAdded { .. } => "context_added",
            TelemetryEvent::ContextRemoved { .. } => "context_removed",
            TelemetryEvent::InstanceGenerated { .. } => "instance_generated",
            TelemetryEvent::InstanceCompleted { .. } => "instance_completed",
            TelemetryEvent::InstanceSkipped { .. } => "instance_skipped",
            TelemetryEvent::TemplateEdited { .. } => "template_edited",
            TelemetryEvent::SyncStarted { .. } => "sync_started",
            TelemetryEvent::SyncCompleted { .. } => "sync_completed",
            TelemetryEvent::SyncFailed { .. } => "sync_failed",
            TelemetryEvent::ConflictResolved { .. } => "conflict_resolved",
            TelemetryEvent::WorkspaceOpened { .. } => "workspace_opened",
            TelemetryEvent::FileParsed { .. } => "file_parsed",
            TelemetryEvent::LspStarted { .. } => "lsp_started",
        }
    }
}

/// A complete telemetry record ready for NDJSON serialization.
///
/// This is the envelope structure that wraps a [`TelemetryEvent`] with
/// common metadata fields (timestamp, tool, action_uuid).
///
/// # Serialization
///
/// The record is serialized as a flat JSON object with the event fields
/// merged in (via `#[serde(flatten)]`):
///
/// ```json
/// {
///   "timestamp": "2026-01-30T10:30:00+00:00",
///   "tool": "cli",
///   "action_uuid": "abc-123",
///   "event": "action_created",
///   "name": "My task",
///   "file_path": "inbox.actions"
/// }
/// ```
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct TelemetryRecord {
    /// ISO 8601 timestamp when the event occurred
    pub timestamp: String,
    /// Tool that generated this event
    pub tool: Tool,
    /// Related action UUID (if applicable)
    #[serde(skip_serializing_if = "Option::is_none")]
    pub action_uuid: Option<String>,
    /// The semantic event data
    #[serde(flatten)]
    pub event: TelemetryEvent,
}

impl TelemetryRecord {
    /// Create a new telemetry record with the current UTC timestamp.
    ///
    /// # Arguments
    ///
    /// * `tool` - The tool generating this event
    /// * `action_uuid` - Optional UUID of the related action
    /// * `event` - The semantic event data
    ///
    /// # Example
    ///
    /// ```rust,ignore
    /// let record = TelemetryRecord::new(
    ///     Tool::Cli,
    ///     Some("abc-123".to_string()),
    ///     TelemetryEvent::ActionDeleted { name: "My task".to_string() },
    /// );
    /// ```
    pub fn new(tool: Tool, action_uuid: Option<String>, event: TelemetryEvent) -> Self {
        Self {
            timestamp: Utc::now().to_rfc3339(),
            tool,
            action_uuid,
            event,
        }
    }

    /// Create a new telemetry record with a specific timestamp.
    ///
    /// This is useful for backfilling historical events or preserving
    /// the original timestamp when an event is recorded after-the-fact.
    ///
    /// # Arguments
    ///
    /// * `timestamp` - The timestamp to use for this event
    /// * `tool` - The tool generating this event
    /// * `action_uuid` - Optional UUID of the related action
    /// * `event` - The semantic event data
    pub fn with_timestamp(
        timestamp: DateTime<Utc>,
        tool: Tool,
        action_uuid: Option<String>,
        event: TelemetryEvent,
    ) -> Self {
        Self {
            timestamp: timestamp.to_rfc3339(),
            tool,
            action_uuid,
            event,
        }
    }
}

/// Get the XDG state directory for ClearHead telemetry.
///
/// Returns the path where telemetry files are stored:
/// - **Linux:** `~/.local/state/clearhead/telemetry/` (or `$XDG_STATE_HOME/clearhead/telemetry/`)
/// - **macOS:** `~/Library/Application Support/clearhead/telemetry/`
/// - **Windows:** `%LOCALAPPDATA%\clearhead\state\telemetry\`
///
/// The directory is created automatically when events are emitted.
pub fn get_telemetry_dir() -> PathBuf {
    let state_dir = dirs::state_dir()
        .or_else(|| {
            // Fallback for systems without XDG_STATE_HOME
            dirs::data_local_dir().map(|p| p.join("state"))
        })
        .unwrap_or_else(|| {
            dirs::home_dir()
                .expect("Could not determine home directory")
                .join(".local")
                .join("state")
        });

    state_dir.join("clearhead").join("telemetry")
}

/// Get the current month's telemetry file path.
///
/// Files are named `events-YYYY-MM.ndjson` for monthly rotation.
fn get_current_file() -> PathBuf {
    let now = Utc::now();
    let filename = format!("events-{}.ndjson", now.format("%Y-%m"));
    get_telemetry_dir().join(filename)
}

/// Initialize the telemetry subsystem by ensuring the directory exists.
///
/// This is called automatically by [`emit`], but can be called explicitly
/// during application startup to fail fast if permissions are wrong.
///
/// # Errors
///
/// Returns an error if the directory cannot be created.
pub fn init() -> Result<(), String> {
    let dir = get_telemetry_dir();
    fs::create_dir_all(&dir).map_err(|e| format!("Failed to create telemetry directory: {}", e))
}

/// Emit a telemetry record to the NDJSON file.
///
/// This function:
/// 1. Ensures the telemetry directory exists
/// 2. Serializes the record to JSON
/// 3. Appends it to the current month's file
/// 4. Logs via tracing for operational visibility
///
/// # Arguments
///
/// * `record` - The complete telemetry record to emit
///
/// # Errors
///
/// Returns an error if:
/// - The telemetry directory cannot be created
/// - The record cannot be serialized
/// - The file cannot be written
///
/// # Example
///
/// ```rust,ignore
/// let record = TelemetryRecord::new(
///     Tool::Cli,
///     Some("abc-123".to_string()),
///     TelemetryEvent::ActionCreated {
///         name: "My task".to_string(),
///         file_path: "inbox.actions".to_string(),
///     },
/// );
/// emit(record)?;
/// ```
pub fn emit(record: TelemetryRecord) -> Result<(), String> {
    // Ensure directory exists
    init()?;

    // Serialize to JSON
    let json =
        serde_json::to_string(&record).map_err(|e| format!("Failed to serialize event: {}", e))?;

    // Append to file
    let file_path = get_current_file();
    let mut file = OpenOptions::new()
        .create(true)
        .append(true)
        .open(&file_path)
        .map_err(|e| format!("Failed to open telemetry file: {}", e))?;

    writeln!(file, "{}", json).map_err(|e| format!("Failed to write event: {}", e))?;

    // Also log for operational visibility (journald, stderr)
    info!(
        event = record.event.name(),
        action_uuid = ?record.action_uuid,
        tool = ?record.tool,
        "telemetry"
    );

    Ok(())
}

/// Convenience function to emit an event with the current timestamp.
///
/// This is the most common way to emit telemetry events. It automatically
/// creates a [`TelemetryRecord`] with the current UTC timestamp.
///
/// # Arguments
///
/// * `tool` - The tool generating this event (Cli, Lsp, or Sync)
/// * `action_uuid` - Optional UUID of the related action
/// * `event` - The semantic event to emit
///
/// # Errors
///
/// See [`emit`] for error conditions.
///
/// # Example
///
/// ```rust,ignore
/// // Emit when an action is completed
/// emit_event(
///     Tool::Cli,
///     Some(action.id.to_string()),
///     TelemetryEvent::ActionCompleted {
///         name: action.name.clone(),
///         completed_at: chrono::Utc::now().to_rfc3339(),
///     },
/// )?;
/// ```
pub fn emit_event(
    tool: Tool,
    action_uuid: Option<String>,
    event: TelemetryEvent,
) -> Result<(), String> {
    let record = TelemetryRecord::new(tool, action_uuid, event);
    emit(record)
}

